package com.arrl.radiocraft.client.render;

/**
 * A tiny 5 x 7 pixel font for words drawn into a CRT monitor's picture (2026-11-15: "WAITING FOR SATELLITE PASS" on a
 * screen with nothing to show yet), so the words are part of the tube's texture and line up across a wall of monitors
 * like the pictures do. Capital letters, digits and a few marks; anything else is a space. Pure; unit tested.
 */
public final class CrtText {

	/** A glyph's size, and the gap after it, pixels (before scaling). */
	public static final int W = 5, H = 7, GAP = 1, LINE_GAP = 3;

	private static final String CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.:-";
	// Each glyph: seven rows of five bits, top first, the left pixel the high bit.
	private static final int[][] GLYPHS = {
			{ 0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 }, // A
			{ 0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E }, // B
			{ 0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E }, // C
			{ 0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E }, // D
			{ 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F }, // E
			{ 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10 }, // F
			{ 0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F }, // G
			{ 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 }, // H
			{ 0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E }, // I
			{ 0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C }, // J
			{ 0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11 }, // K
			{ 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F }, // L
			{ 0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11 }, // M
			{ 0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11 }, // N
			{ 0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E }, // O
			{ 0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10 }, // P
			{ 0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D }, // Q
			{ 0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11 }, // R
			{ 0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E }, // S
			{ 0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04 }, // T
			{ 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E }, // U
			{ 0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04 }, // V
			{ 0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A }, // W
			{ 0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11 }, // X
			{ 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04 }, // Y
			{ 0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F }, // Z
			{ 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E }, // 0
			{ 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E }, // 1
			{ 0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F }, // 2
			{ 0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E }, // 3
			{ 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02 }, // 4
			{ 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E }, // 5
			{ 0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E }, // 6
			{ 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08 }, // 7
			{ 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E }, // 8
			{ 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C }, // 9
			{ 0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C }, // .
			{ 0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00 }, // :
			{ 0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00 }, // -
	};

	private CrtText() {}

	/** True if glyph pixel {@code x, y} of {@code c} is lit. */
	public static boolean lit(char c, int x, int y) {
		int i = CHARS.indexOf(Character.toUpperCase(c));
		if(i < 0 || x < 0 || x >= W || y < 0 || y >= H)
			return false;
		return (GLYPHS[i][y] >> (W - 1 - x) & 1) != 0;
	}

	/** Pixels across {@code text} at {@code scale}. */
	public static int width(String text, int scale) {
		return text.isEmpty() ? 0 : (text.length() * (W + GAP) - GAP) * scale;
	}

	/**
	 * A mask {@code width} by {@code height} (row by row) with {@code lines} centred in it, each as large as fits (scale
	 * 1 to 4, the same for every line): true where a letter is lit. All false if even scale 1 does not fit.
	 */
	public static boolean[] mask(int width, int height, String... lines) {
		boolean[] out = new boolean[width * height];
		int widest = 0;
		for(String line : lines)
			widest = Math.max(widest, width(line, 1));
		int scale = 0;
		for(int s = 4; s >= 1 && scale == 0; s--)
			if(widest * s <= width - 4 * s && (lines.length * (H + LINE_GAP) - LINE_GAP) * s <= height - 4 * s)
				scale = s;
		if(scale == 0)
			return out;
		int total = (lines.length * (H + LINE_GAP) - LINE_GAP) * scale;
		int top = (height - total) / 2;
		for(int l = 0; l < lines.length; l++) {
			String line = lines[l];
			int left = (width - width(line, scale)) / 2, y0 = top + l * (H + LINE_GAP) * scale;
			for(int c = 0; c < line.length(); c++)
				for(int gy = 0; gy < H; gy++)
					for(int gx = 0; gx < W; gx++)
						if(lit(line.charAt(c), gx, gy))
							for(int dy = 0; dy < scale; dy++)
								for(int dx = 0; dx < scale; dx++) {
									int x = left + (c * (W + GAP) + gx) * scale + dx, y = y0 + gy * scale + dy;
									if(x >= 0 && x < width && y >= 0 && y < height)
										out[x + y * width] = true;
								}
		}
		return out;
	}
}
